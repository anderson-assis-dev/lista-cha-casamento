import{Router,type IRouter}from"express";
import{convidadoController,presenteController,configuracaoController,authController}from"../controllers/index.js";
import{validateBody}from"../middlewares/error.js";
import{authMiddleware}from"../middlewares/auth.js";
import{createConvidadoSchema,updateConvidadoSchema,reservarSchema,outroSchema,pixSchema,presenteSchema,updatePresenteSchema,loginSchema,configuracaoSchema}from"../dtos/index.js";
export const publicRouter:IRouter=Router();
publicRouter.post("/convidados",validateBody(createConvidadoSchema),convidadoController.create);
publicRouter.post("/convidados/:id/presentes",validateBody(reservarSchema),convidadoController.reservar);
publicRouter.post("/convidados/:id/outro",validateBody(outroSchema),convidadoController.outro);
publicRouter.post("/convidados/:id/pix",validateBody(pixSchema),convidadoController.pix);
publicRouter.get("/presentes",convidadoController.presentesPublicos);
export const adminRouter:IRouter=Router();
adminRouter.post("/login",validateBody(loginSchema),authController.login);
adminRouter.use(authMiddleware);
adminRouter.get("/dashboard",convidadoController.dashboard);
adminRouter.get("/convidados",convidadoController.list);
adminRouter.put("/convidados/:id",validateBody(updateConvidadoSchema),convidadoController.update);
adminRouter.delete("/convidados/:id",convidadoController.remove);
adminRouter.get("/presentes",presenteController.list);
adminRouter.post("/presentes",validateBody(presenteSchema),presenteController.create);
adminRouter.put("/presentes/:id",validateBody(updatePresenteSchema),presenteController.update);
adminRouter.delete("/presentes/:id",presenteController.remove);
adminRouter.get("/configuracoes",configuracaoController.get);
adminRouter.put("/configuracoes",validateBody(configuracaoSchema),configuracaoController.update);
adminRouter.get("/export/csv",convidadoController.exportCsv);
adminRouter.get("/export/excel",convidadoController.exportExcel);
